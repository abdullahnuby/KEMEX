#!/usr/bin/env node
// Parses supabase/migrations/*.sql (in order) to reconstruct the FINAL live
// RLS policy set per table (accounting for every drop/recreate across the
// whole history), then emits a new migration that:
//   1. adds tenant_id to every real business table (skipping tenants/
//      profiles/organization_settings, which migration 032 already handles)
//   2. rewrites every existing policy to AND-in a tenant check
//   3. backfills tenant_id for pre-existing rows into the default tenant
//
// This is generated, reviewable SQL — inspect the output file before
// applying it to any real database.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const migrationsDir = path.join(__dirname, '..', 'supabase', 'migrations')

// Tables that must NOT get a bare tenant_id retrofit here (handled by hand
// in 032, or are legitimately platform-global rather than per-tenant).
const SKIP_TABLES = new Set([
  'tenants',
  'profiles',
  'organization_settings',
  'release_registry', // platform software-release metadata, not tenant data
])

const files = fs.readdirSync(migrationsDir)
  .filter(f => /^\d+_.*\.sql$/.test(f))
  .filter(f => f !== '033_multi_tenant_retrofit.sql') // never read our own generated output back in
  .sort()

/** @type {Record<string, Record<string, {cmd:string, to:string, using:string, check:string}>>} */
const policies = {}
/** @type {Set<string>} */
const rlsTables = new Set()
/** @type {Set<string>} */
const allTables = new Set()

function stripComments(sql) {
  return sql.split('\n').map(line => {
    const idx = line.indexOf('--')
    return idx === -1 ? line : line.slice(0, idx)
  }).join('\n')
}

for (const file of files) {
  const raw = fs.readFileSync(path.join(migrationsDir, file), 'utf8')
  const sql = stripComments(raw)
  const statements = sql.split(';')

  for (const stmtRaw of statements) {
    const stmt = stmtRaw.trim()
    if (!stmt) continue

    let m
    if ((m = stmt.match(/create table (?:if not exists )?public\.(\w+)/i))) {
      allTables.add(m[1])
      continue
    }
    if ((m = stmt.match(/alter table (?:if exists )?public\.(\w+)\s+enable row level security/i))) {
      rlsTables.add(m[1])
      continue
    }
    if ((m = stmt.match(/drop policy if exists (\w+)\s+on\s+public\.(\w+)/i))) {
      const [, name, table] = m
      if (policies[table]) delete policies[table][name]
      continue
    }
    if ((m = stmt.match(/create policy (\w+)\s+on\s+public\.(\w+)\s+for\s+(\w+)([\s\S]*)$/i))) {
      const [, name, table, cmd, rest] = m
      const toMatch = rest.match(/to\s+([\w, ]+?)(?:\s+using|\s+with check|$)/i)
      const usingMatch = rest.match(/using\s*\(([\s\S]*?)\)\s*(?:with check|$)/i)
      const checkMatch = rest.match(/with check\s*\(([\s\S]*)\)\s*$/i)
      policies[table] = policies[table] || {}
      policies[table][name] = {
        cmd: cmd.toLowerCase(),
        to: toMatch ? toMatch[1].trim() : 'authenticated',
        using: usingMatch ? usingMatch[1].trim() : '',
        check: checkMatch ? checkMatch[1].trim() : '',
      }
      continue
    }
  }
}

const tenantTables = [...allTables].filter(t => !SKIP_TABLES.has(t)).sort()

let out = `-- 033_multi_tenant_retrofit.sql
-- GENERATED by scripts/generate-tenant-migration.mjs — review before applying.
-- Adds tenant_id to every business table and rewrites every existing RLS
-- policy (as reconstructed from the full migration history) to require
-- tenant_id = private.current_tenant_id(). Existing rows are backfilled
-- into the default tenant created in 032_multi_tenant_foundation.sql.

do $$
begin
  if not exists (select 1 from public.tenants where slug = 'default') then
    raise exception 'Run 032_multi_tenant_foundation.sql first (no default tenant found).';
  end if;
end $$;

`

for (const table of tenantTables) {
  out += `-- ---------- ${table} ----------\n`
  out += `alter table public.${table} add column if not exists tenant_id uuid references public.tenants(id);\n`
  out += `update public.${table} set tenant_id = (select id from public.tenants where slug = 'default') where tenant_id is null;\n`
  out += `alter table public.${table} alter column tenant_id set default private.current_tenant_id();\n`
  out += `alter table public.${table} alter column tenant_id set not null;\n`
  out += `create index if not exists ${table}_tenant_idx on public.${table}(tenant_id);\n`

  const tablePolicies = policies[table] || {}
  const names = Object.keys(tablePolicies)
  if (names.length === 0 && rlsTables.has(table)) {
    out += `-- NOTE: ${table} has RLS enabled but no policy was reconstructed from history — verify manually.\n`
  }
  for (const name of names) {
    const p = tablePolicies[name]
    const tenantCond = 'tenant_id = private.current_tenant_id()'
    const isInsertOnly = p.cmd === 'insert'
    const using = p.using ? `(${p.using}) and ${tenantCond}` : tenantCond
    const check = p.check ? `(${p.check}) and ${tenantCond}` : (isInsertOnly || p.cmd === 'all' ? tenantCond : '')
    out += `drop policy if exists ${name} on public.${table};\n`
    out += `create policy ${name} on public.${table} for ${p.cmd} to ${p.to}`
    if (!isInsertOnly) out += ` using (${using})`
    if (check) out += ` with check (${check})`
    out += `;\n`
  }
  out += '\n'
}

const outPath = path.join(migrationsDir, '033_multi_tenant_retrofit.sql')
fs.writeFileSync(outPath, out, 'utf8')
console.log(`Wrote ${outPath}`)
console.log(`Tables retrofitted: ${tenantTables.length}`)
console.log(`Tables skipped (handled elsewhere): ${[...SKIP_TABLES].join(', ')}`)
const noPolicyTables = tenantTables.filter(t => !policies[t] || Object.keys(policies[t]).length === 0)
if (noPolicyTables.length) console.log(`Tables with NO reconstructed policy (check manually): ${noPolicyTables.join(', ')}`)
